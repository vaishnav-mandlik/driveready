#!/usr/bin/env node
/**
 * Regenerates src/content/index.ts with lazy `require` loaders for every
 * content JSON file, so adding/removing content never needs code edits.
 *
 *   node scripts/build-content-index.mjs
 */
import {existsSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(APP, 'src', 'content');
const TRACKS = ['car', 'motorcycle', 'cdl'];

const jsonFiles = dir =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter(f => f.endsWith('.json') && !f.startsWith('_'))
        .sort()
        .map(f => join(dir, f))
    : [];

const walk = dir => {
  if (!existsSync(dir)) {
    return [];
  }
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      out.push(...walk(p));
    } else if (name.endsWith('.json') && !name.startsWith('_')) {
      out.push(p);
    }
  }
  return out;
};

const rel = p => './' + relative(CONTENT, p).split('\\').join('/');
const code = p => p.split('/').pop().replace('.json', '');

const lines = [];
lines.push('/* AUTO-GENERATED by scripts/build-content-index.mjs — do not edit by hand. */');
lines.push("import type {Lesson, Question, StateCode, StateInfo, TrackId} from '../data/types';");
lines.push('');
lines.push('export const universalQuestionLoaders: Record<TrackId, Array<() => Question[]>> = {');
for (const t of TRACKS) {
  const files = jsonFiles(join(CONTENT, 'questions', t));
  lines.push(`  ${t}: [`);
  for (const f of files) {
    lines.push(`    () => require('${rel(f)}'),`);
  }
  lines.push('  ],');
}
lines.push('};');
lines.push('');
lines.push('export const stateQuestionLoaders: Partial<Record<StateCode, () => Question[]>> = {');
for (const f of jsonFiles(join(CONTENT, 'questions', 'states'))) {
  lines.push(`  ${code(f)}: () => require('${rel(f)}'),`);
}
lines.push('};');
lines.push('');
lines.push('export const stateInfoLoaders: Partial<Record<StateCode, () => StateInfo>> = {');
for (const f of jsonFiles(join(CONTENT, 'states'))) {
  lines.push(`  ${code(f)}: () => require('${rel(f)}'),`);
}
lines.push('};');
lines.push('');
lines.push('export const lessonLoaders: Array<() => Lesson> = [');
for (const f of walk(join(CONTENT, 'lessons'))) {
  lines.push(`  () => require('${rel(f)}'),`);
}
lines.push('];');
lines.push('');

writeFileSync(join(CONTENT, 'index.ts'), lines.join('\n'));
console.log(`wrote ${relative(APP, join(CONTENT, 'index.ts'))}`);

export type IconName = keyof typeof ICONS;

export type IconColor =
  | 'text'
  | 'textMuted'
  | 'textFaint'
  | 'primary'
  | 'success'
  | 'danger'
  | 'warning'
  | 'accent'
  | 'gold'
  | 'onPrimary';

export interface IconProps {
  name: IconName;
  size?: number;
  /** Theme color key, or any literal color string. */
  color?: IconColor | (string & {});
  strokeWidth?: number;
  fill?: string;
}

export function Icon({name, size = 22, color = 'text', strokeWidth = 2, fill}: IconProps) {
  const {colors} = useTheme();
  const Cmp = ICONS[name];
  const resolved = (colors as unknown as Record<string, string>)[color] ?? color;
  return <Cmp size={size} color={resolved} strokeWidth={strokeWidth} fill={fill ?? 'none'} />;
}

export const ICON_NAMES = Object.keys(ICONS) as IconName[];
